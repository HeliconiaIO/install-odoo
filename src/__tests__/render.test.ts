import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { computeOdooTuning, isSafeAbsolutePath, isValidIdentifier, odooVersionOsError, shellQuote } from '@helpers/system';
import { validateConfig } from '@helpers/validate';
import { renderOdooConfig } from '@setup/config';
import { fixNginxConfigText, parseOdooConf, upsertOdooConf } from '@setup/doctor';
import { renderNginxConfig } from '@setup/nginx';
import { renderLogrotate, renderServiceUnit } from '@setup/service';

describe('systemd unit', () => {
  const unit = renderServiceUnit({ odooUser: 'odoo', odooHome: '/odoo', localPostgres: true });

  it('runs Odoo in the foreground and restarts it on failure', () => {
    assert.match(unit, /^Type=simple$/m);
    assert.match(unit, /^Restart=on-failure$/m);
    assert.doesNotMatch(unit, /RemainAfterExit/);
    assert.match(unit, /^ExecStart=\/odoo\/venv\/bin\/python3 \/odoo\/odoo-server\/odoo-bin --config=\/etc\/odoo-server\.conf$/m);
  });

  it('orders after PostgreSQL only when it is local', () => {
    assert.match(unit, /After=network\.target postgresql\.service/);
    assert.doesNotMatch(renderServiceUnit({ odooUser: 'odoo', odooHome: '/odoo' }), /postgresql/);
  });

  it('uses the service user and name', () => {
    const custom = renderServiceUnit({ odooUser: 'erp', odooHome: '/srv/erp' });
    assert.match(custom, /^User=erp$/m);
    assert.match(custom, /^SyslogIdentifier=erp-server$/m);
    assert.match(custom, /--config=\/etc\/erp-server\.conf/);
  });
});

describe('logrotate', () => {
  it('rotates the directory Odoo really logs to, with copytruncate', () => {
    const rule = renderLogrotate('odoo');
    assert.match(rule, /^\/var\/log\/odoo\/\*\.log \{/);
    assert.match(rule, /copytruncate/);
  });
});

describe('odoo.conf', () => {
  const config = renderOdooConfig(
    { odooUser: 'odoo', odooHome: '/odoo', isEnterprise: false, pgHost: 'localhost', pgPort: 5432, pgUser: 'odoo', pgPassword: 'pw', httpPort: 8069, geventPort: 8072, nginx: true, adminPassword: 'secretsecret' },
    computeOdooTuning(4, 8 * 1024 ** 3),
  );
  const parsed = parseOdooConf(config);

  it('contains workers and limits', () => {
    assert.equal(parsed.workers, '8');
    assert.equal(parsed.max_cron_threads, '2');
    assert.ok(Number(parsed.limit_memory_hard) > Number(parsed.limit_memory_soft));
    assert.equal(parsed.proxy_mode, 'True');
    assert.equal(parsed.logfile, '/var/log/odoo/odoo-server.log');
  });

  it('is not indented (Odoo would read indented keys as continuation lines)', () => {
    assert.match(config, /^\[options\]/);
    assert.doesNotMatch(config, /^\s+\w+ =/m);
  });
});

describe('tuning', () => {
  it('never runs threaded and respects small servers', () => {
    const small = computeOdooTuning(1, 1024 ** 3);
    assert.equal(small.workers, 2);
    assert.equal(small.limitMemorySoft, 512 * 1024 * 1024);
  });
  it('caps workers by CPU and RAM', () => {
    assert.equal(computeOdooTuning(2, 64 * 1024 ** 3).workers, 4);
    assert.equal(computeOdooTuning(32, 4 * 1024 ** 3).workers, 4);
  });
  it('keeps the soft limit at or below 2GB', () => {
    assert.equal(computeOdooTuning(8, 128 * 1024 ** 3).limitMemorySoft, 2048 * 1024 * 1024);
  });
});

describe('nginx', () => {
  it('only sets secure cookies and HSTS with SSL', () => {
    assert.doesNotMatch(renderNginxConfig(8069, 8072, 'erp.example.com', false), /secure|Strict-Transport/);
    const withSsl = renderNginxConfig(8069, 8072, 'erp.example.com', true);
    assert.equal((withSsl.match(/proxy_cookie_flags/g) ?? []).length, 2);
  });
  it('proxies websockets over HTTP/1.1 and allows uploads', () => {
    const conf = renderNginxConfig(8069, 8072, 'erp.example.com');
    assert.match(conf, /proxy_pass http:\/\/127\.0\.0\.1:8072;\n\s+proxy_http_version 1\.1;/);
    assert.match(conf, /client_max_body_size 100m;/);
  });
  it('doctor leaves a freshly generated config untouched', () => {
    for (const ssl of [false, true]) {
      const conf = renderNginxConfig(8069, 8072, 'erp.example.com', ssl);
      // certbot adds TLS directives; emulate it for the ssl variant
      const text = ssl ? `${conf}\n# listen 443 ssl; ssl_certificate x;` : conf;
      assert.equal(fixNginxConfigText(text, 8072), text);
    }
  });
  it('doctor repairs the config generated by 1.0.x', () => {
    const legacy = `server {
  listen 80;
  server_name erp.example.com;
  location /websocket {
    proxy_pass http://127.0.0.1:8072;
    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains";
    proxy_cookie_flags session_id samesite=lax secure;  # requires nginx 1.19.8
  }
}`;
    const fixed = fixNginxConfigText(legacy, 8072);
    assert.match(fixed, /proxy_http_version 1\.1;/);
    assert.match(fixed, /client_max_body_size 100m;/);
    assert.doesNotMatch(fixed, /secure|Strict-Transport/);
  });
});

describe('doctor config helpers', () => {
  it('upserts keys without touching the rest', () => {
    const text = '[options]\nadmin_passwd = x\nworkers = 0\n';
    const updated = upsertOdooConf(upsertOdooConf(text, 'workers', 4), 'limit_time_real', 1200);
    assert.deepEqual(parseOdooConf(updated), { admin_passwd: 'x', workers: '4', limit_time_real: '1200' });
  });
});

describe('validation', () => {
  const valid = {
    version: '18.0', odooHome: '/odoo', odooUser: 'odoo', httpPort: 8069, geventPort: 8072,
    pgHost: 'localhost', pgPort: 5432, pgUser: 'odoo', pgPassword: 'pw', strongPassword: true, nginx: false,
  };
  it('accepts a valid config', () => assert.deepEqual(validateConfig(valid), []));
  it('rejects shell metacharacters', () => {
    assert.ok(validateConfig({ ...valid, odooUser: 'odoo; rm -rf /' }).length > 0);
    assert.ok(validateConfig({ ...valid, odooHome: '/odoo; rm -rf /' }).length > 0);
    assert.ok(validateConfig({ ...valid, pgUser: 'x"; DROP' }).length > 0);
  });
  it('rejects equal ports and bad versions', () => {
    assert.ok(validateConfig({ ...valid, geventPort: 8069 }).length > 0);
    assert.ok(validateConfig({ ...valid, version: '12.0' }).length > 0);
  });
  it('accepts Odoo 20.0', () => assert.deepEqual(validateConfig({ ...valid, version: '20.0' }), []));
  it('needs Ubuntu 24.04 for Odoo 20.0 (Python 3.12)', () => {
    assert.match(odooVersionOsError('20.0', '22.04') ?? '', /Ubuntu 24.04/);
    assert.equal(odooVersionOsError('20.0', '24.04'), null);
    assert.equal(odooVersionOsError('19.0', '22.04'), null);
  });
  it('requires a real domain and email for SSL', () => {
    assert.ok(validateConfig({ ...valid, nginx: true, websiteName: '_', ssl: true, sslEmail: 'a@b.co' }).length > 0);
    assert.deepEqual(validateConfig({ ...valid, nginx: true, websiteName: 'erp.example.com', ssl: true, sslEmail: 'a@b.co' }), []);
  });
  it('quotes and identifies safely', () => {
    assert.equal(shellQuote("a'b"), `'a'\\''b'`);
    assert.ok(isValidIdentifier('odoo-18'));
    assert.ok(!isValidIdentifier('Odoo'));
    assert.ok(isSafeAbsolutePath('/opt/odoo'));
    assert.ok(!isSafeAbsolutePath('/opt/../etc'));
  });
});
